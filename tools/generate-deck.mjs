#!/usr/bin/env node
// FilmDeck generator: storyboard.json -> validate -> render recipes -> scenes.js / scenes.css / deck.json -> index.html -> QA.
// usage: node tools/generate-deck.mjs <storyboard.json> [--out <dir>] [--no-qa]
import fs from 'fs'; import path from 'path'; import crypto from 'crypto'; import { spawnSync } from 'child_process'; import { fileURLToPath } from 'url';
import { validateStoryboard, resolveSceneInputs, resolvedFact } from './validate-storyboard.mjs';
import { buildDeck } from './build-deck.mjs';
import { recipes } from '../engine/recipes/index.mjs';
import { renderTemplates, MOODS, jsonData, esc } from '../engine/recipes/_lib.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATOR_VERSION = 2;
const TONE_VARS = { accent: 'var(--ember)', secondary: 'var(--signal)', neutral: 'var(--paper)', negative: 'var(--alarm)', positive: 'var(--sage)' };

const args = process.argv.slice(2); const file = args.find(a => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--out');
if (!file) { console.error('usage: node tools/generate-deck.mjs <storyboard.json> [--out <dir>] [--no-qa]'); process.exit(2); }
const fail = (m, code = 1) => { console.error(m); process.exit(code); };

const raw = fs.readFileSync(file, 'utf8'); const sb = JSON.parse(raw);
const report = validateStoryboard(sb);
report.warnings.filter(w => !/number word/.test(w)).forEach(w => console.log('warning', w));
if (report.errors.length) { report.errors.forEach(e => console.error('ERROR  ', e)); fail(`storyboard invalid: ${report.errors.length} error(s), nothing generated`); }
console.log('storyboard valid:', report.info[report.info.length - 1]);

const outDir = path.resolve(args.includes('--out') ? args[args.indexOf('--out') + 1] : path.join(root, 'generated', sb.deck.id));
// Only this generator's own outputs are replaced, so a project folder can also hold source.json, run.json etc.
fs.mkdirSync(outDir, { recursive: true });
for (const f of ['index.html', 'scenes.js', 'scenes.css', 'deck.json', 'storyboard.json', 'qa-report.json', 'qa-output']) fs.rmSync(path.join(outDir, f), { recursive: true, force: true });

const facts = new Map(sb.facts.map(f => [f.id, f]));
const pad2 = n => String(n).padStart(2, '0');
let js = `/* Generated by FilmDeck generator v${GENERATOR_VERSION} from storyboard "${sb.deck.id}". Do not edit by hand; edit the storyboard and regenerate. */\n` +
  `const FD_ESC=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));\n`;
let css = '';
const sceneMeta = [], allowedNumberStrings = new Set(sb.facts.map(f => f.display));

sb.scenes.forEach((sc, idx) => {
  const n = idx + 1, recipe = recipes[sc.recipe];
  const { inputs, used, errors } = resolveSceneInputs(sc, facts, recipe); if (errors.length) fail(errors.join('\n'));
  const data = { ...inputs, kicker: `Scene ${pad2(n)} · ${sc.kicker}`, title: sc.title || '', toneVars: TONE_VARS, toneVar: TONE_VARS[inputs.afterTone] || TONE_VARS.negative };
  // tick labels shown by chart recipes are generated from the declared scale: record them as allowed on-screen numbers
  if (inputs.scale) { const S = inputs.scale; const step = Math.min(S.minorStep || Infinity, S.step || Infinity, S.majorStep); for (let v = S.min; v <= S.max + 1e-9; v += step) allowedNumberStrings.add(String(+v.toFixed(6))); }
  const out = renderTemplates(recipe.id, { sid: `s${n}`, P: `S${n}`, C: `s${n}`, chapter: sc.chapter, mood: MOODS[sc.mood], letterbox: sc.letterbox ?? recipe.letterbox, data });
  allowedNumberStrings.add(data.kicker); (recipe.structuralLabels ? recipe.structuralLabels(inputs) : []).forEach(l => allowedNumberStrings.add(l));
  js += out.js; css += out.css + '\n';
  const refs = [...used].map(id => ({ fact: id, display: facts.get(id).display, sourceRef: facts.get(id).sourceRef || null, derivedFrom: facts.get(id).derivation ? facts.get(id).derivation.of : undefined }));
  // derived facts also carry the sources of what they derive from
  const sources = new Set(); used.forEach(id => { const f = facts.get(id); if (f.sourceRef) sources.add(f.sourceRef); (f.derivation?.of || []).forEach(r => { const g = facts.get(r.split('.')[0]); if (g?.sourceRef) sources.add(g.sourceRef); }); });
  sceneMeta.push({ id: sc.id, section: `s${n}`, n, chapter: sc.chapter, recipe: recipe.id, mood: sc.mood, letterbox: sc.letterbox ?? recipe.letterbox,
    beats: sc.beats.map(b => ({ n: b.n, notes: b.notes, summary: b.summary || null })), sourceRefs: refs, sources: [...sources],
    textZones: ((recipe.capabilities && recipe.capabilities.textZones) || []).map(z => ({ ...z, selector: z.selector.split('__C__').join(`s${n}`) })) });
});

const accent = sb.deck.titleAccent || '';
const introTitle = accent && sb.deck.title.includes(accent) ? sb.deck.title.split(accent).map(esc).join(`<em>${esc(accent)}</em>`) : esc(sb.deck.title);
const N = sb.scenes.length;
const helpDigits = N <= 9 ? `<div><b>1 to ${N}</b><br>jump to scene</div>` : '<div><b>1 to 9</b><br>jump to scene (N / P for the rest)</div>';
const deckJson = {
  title: esc(sb.deck.title), introKicker: esc(sb.deck.subtitle), introTitle, introParagraph: esc(sb.deck.intro), helpDigits,
  sections: sceneMeta.map(m => m.section),
  generator: { version: GENERATOR_VERSION, offline: true, gsap: '3.12.5', storyboardSha256: crypto.createHash('sha256').update(raw).digest('hex'), deckId: sb.deck.id, fictional: !!sb.deck.fictional },
  sources: sb.sources, facts: sb.facts, scenes: sceneMeta, allowedNumberStrings: [...allowedNumberStrings]
};
const meta = { deckId: sb.deck.id, fictional: !!sb.deck.fictional, sources: sb.sources, facts: sb.facts, scenes: sceneMeta, allowedNumberStrings: deckJson.allowedNumberStrings };
js += `\n/* machine-readable deck metadata: speaker notes and source references (never displayed) */\nwindow.__filmdeckMeta=${jsonData(meta)};\n`;

fs.writeFileSync(path.join(outDir, 'scenes.js'), js); fs.writeFileSync(path.join(outDir, 'scenes.css'), css);
fs.writeFileSync(path.join(outDir, 'deck.json'), JSON.stringify(deckJson, null, 2));
fs.writeFileSync(path.join(outDir, 'storyboard.json'), raw);
const built = buildDeck(outDir, path.join(outDir, 'index.html'), { offline: true });
console.log(`generated ${N} scenes, ${sceneMeta.reduce((a, s) => a + s.beats.length, 0)} beats -> ${path.relative(process.cwd(), built.outFile)} (${built.bytes} bytes)`);

if (!args.includes('--no-qa')) {
  const r = spawnSync(process.execPath, [path.join(root, 'tests/generated/qa.mjs'), outDir], { stdio: 'inherit', env: process.env });
  if (r.status !== 0) fail('QA FAILED: the generated deck is not acceptable. Fix the generator or recipe, do not patch the output.');
  console.log('QA passed');
}
